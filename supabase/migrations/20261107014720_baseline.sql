CREATE TABLE "public"."hmrc_user_tokens" (
  "user_id"                  bigint                   NOT NULL,
  "access_token_ciphertext"  text                     NOT NULL,
  "access_token_iv"          text                     NOT NULL,
  "refresh_token_ciphertext" text                     NOT NULL,
  "refresh_token_iv"         text                     NOT NULL,
  "encryption_key_version"   text                     NOT NULL DEFAULT 'v1'::text,
  "expires_at"               timestamp with time zone NOT NULL,
  "authorized_at"            timestamp with time zone NOT NULL DEFAULT now(),
  "reauthorization_required" boolean                  NOT NULL DEFAULT false,
  "updated_at"               timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "hmrc_user_tokens_pkey" PRIMARY KEY (user_id)
);

ALTER TABLE "public"."hmrc_user_tokens"
  ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE "public"."hmrc_user_tokens" FROM "anon", "authenticated";

CREATE TABLE "public"."users" (
  "id"            bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "created_at"    timestamp with time zone NOT NULL DEFAULT now(),
  "auth_id"       text,
  "email"         text,
  "ni_number"     character varying,
  "updated_at"    timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc'::text),
  "name"          text                     NOT NULL,
  "allow_cookies" jsonb,
  CONSTRAINT "users_auth0_id_key" UNIQUE (auth_id),
  CONSTRAINT "users_email_key" UNIQUE (email),
  CONSTRAINT "users_ni_number_key" UNIQUE (ni_number),
  CONSTRAINT "users_pkey" PRIMARY KEY (id)
);

ALTER TABLE "public"."users"
  ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.update_timestamp()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  AS $function$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$function$;

ALTER TABLE "public"."hmrc_user_tokens"
  ADD CONSTRAINT "hmrc_user_tokens_user_id_fkey" FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

CREATE TRIGGER update_users_timestamp
  BEFORE UPDATE ON public.users
  FOR EACH ROW
  EXECUTE FUNCTION public.update_timestamp();

COMMENT ON COLUMN "public"."users"."name" IS 'Users full name from Auth0';

COMMENT ON COLUMN "public"."users"."updated_at" IS 'Last time record was edited or accessed.';

