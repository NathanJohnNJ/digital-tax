CREATE TABLE public.record_businesses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  hmrc_business_id text NOT NULL,
  type_of_business text NOT NULL CHECK (
    type_of_business IN ('self-employment', 'uk-property', 'foreign-property')
  ),
  trading_name text,
  is_active boolean NOT NULL DEFAULT true,
  last_synced_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, hmrc_business_id),
  UNIQUE (id, user_id)
);

CREATE TABLE public.digital_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL,
  record_business_id uuid NOT NULL,
  record_date date NOT NULL,
  record_type text NOT NULL CHECK (record_type IN ('income', 'expense')),
  category text NOT NULL,
  description text NOT NULL DEFAULT '',
  source_amount numeric(18, 4) NOT NULL CHECK (source_amount <> 0),
  source_currency char(3) NOT NULL DEFAULT 'GBP',
  amount_gbp numeric(18, 2) NOT NULL CHECK (amount_gbp <> 0),
  exchange_rate numeric(20, 10),
  exchange_rate_date date,
  exchange_rate_source text,
  foreign_property_id uuid,
  foreign_property_country_code char(3),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  archived_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT digital_records_business_owner_fkey
    FOREIGN KEY (record_business_id, user_id)
    REFERENCES public.record_businesses(id, user_id) ON DELETE RESTRICT,
  CONSTRAINT digital_records_currency_conversion_check CHECK (
    (
      source_currency = 'GBP'
      AND amount_gbp = round(source_amount, 2)
      AND exchange_rate IS NULL
      AND exchange_rate_date IS NULL
      AND exchange_rate_source IS NULL
    )
    OR (
      source_currency <> 'GBP'
      AND exchange_rate > 0
      AND exchange_rate_date IS NOT NULL
      AND exchange_rate_source IS NOT NULL
      AND length(trim(exchange_rate_source)) > 0
      AND amount_gbp = round(source_amount * exchange_rate, 2)
    )
  ),
  CONSTRAINT digital_records_foreign_property_check CHECK (
    foreign_property_country_code IS NULL
    OR foreign_property_country_code ~ '^[A-Z]{3}$'
  ),
  UNIQUE (id, user_id)
);

CREATE INDEX digital_records_owner_date_idx
  ON public.digital_records (user_id, record_date DESC, id)
  WHERE archived_at IS NULL;
CREATE INDEX digital_records_business_date_idx
  ON public.digital_records (record_business_id, record_date DESC, id)
  WHERE archived_at IS NULL;

CREATE TABLE public.digital_record_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  digital_record_id uuid NOT NULL,
  record_version integer NOT NULL CHECK (record_version > 0),
  action text NOT NULL CHECK (action IN ('created', 'updated', 'archived')),
  snapshot jsonb NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT digital_record_history_record_owner_fkey
    FOREIGN KEY (digital_record_id, user_id)
    REFERENCES public.digital_records(id, user_id) ON DELETE RESTRICT
);

CREATE INDEX digital_record_history_record_idx
  ON public.digital_record_history (user_id, digital_record_id, occurred_at, id);

CREATE TABLE public.record_import_batches (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  record_business_id uuid NOT NULL,
  status text NOT NULL CHECK (status IN ('committed', 'rejected')),
  source_file_name text,
  content_sha256 char(64) NOT NULL,
  total_rows integer NOT NULL CHECK (total_rows >= 0),
  imported_rows integer NOT NULL CHECK (imported_rows >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT record_import_batches_business_owner_fkey
    FOREIGN KEY (record_business_id, user_id)
    REFERENCES public.record_businesses(id, user_id) ON DELETE RESTRICT,
  UNIQUE (id, user_id)
);

CREATE TABLE public.record_import_rows (
  batch_id uuid NOT NULL,
  user_id bigint NOT NULL,
  row_number integer NOT NULL CHECK (row_number > 0),
  outcome text NOT NULL CHECK (outcome IN ('imported', 'duplicate', 'invalid')),
  normalized_data jsonb NOT NULL,
  error jsonb,
  digital_record_id uuid,
  PRIMARY KEY (batch_id, row_number),
  CONSTRAINT record_import_rows_batch_owner_fkey
    FOREIGN KEY (batch_id, user_id)
    REFERENCES public.record_import_batches(id, user_id) ON DELETE RESTRICT,
  CONSTRAINT record_import_rows_record_owner_fkey
    FOREIGN KEY (digital_record_id, user_id)
    REFERENCES public.digital_records(id, user_id) ON DELETE RESTRICT
);

CREATE TABLE public.record_submission_snapshots (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL,
  record_business_id uuid NOT NULL,
  tax_year char(7) NOT NULL CHECK (tax_year ~ '^[0-9]{4}-[0-9]{2}$'),
  period_start date NOT NULL,
  period_end date NOT NULL,
  payload jsonb NOT NULL,
  outcome text NOT NULL DEFAULT 'pending'
    CHECK (outcome IN ('pending', 'succeeded', 'failed', 'unknown')),
  hmrc_status integer,
  hmrc_correlation_id text,
  hmrc_response jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT record_submission_period_check CHECK (period_end >= period_start),
  CONSTRAINT record_submission_business_owner_fkey
    FOREIGN KEY (record_business_id, user_id)
    REFERENCES public.record_businesses(id, user_id) ON DELETE RESTRICT,
  UNIQUE (id, user_id)
);

CREATE TABLE public.record_submission_items (
  submission_id uuid NOT NULL,
  user_id bigint NOT NULL,
  digital_record_id uuid NOT NULL,
  record_version integer NOT NULL CHECK (record_version > 0),
  record_snapshot jsonb NOT NULL,
  PRIMARY KEY (submission_id, digital_record_id),
  CONSTRAINT record_submission_items_submission_owner_fkey
    FOREIGN KEY (submission_id, user_id)
    REFERENCES public.record_submission_snapshots(id, user_id) ON DELETE RESTRICT,
  CONSTRAINT record_submission_items_record_owner_fkey
    FOREIGN KEY (digital_record_id, user_id)
    REFERENCES public.digital_records(id, user_id) ON DELETE RESTRICT
);

